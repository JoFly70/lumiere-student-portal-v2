const DICT: Record<Language, Record<string, string>> = { en: djEn, fr: djFr };

/** Pure translate (used by the hook and by tests). */
export function djTranslate(lang: Language, key: DjKey, vars?: Record<string, string | number>): string {
  const raw = DICT[lang]?.[key] ?? djEn[key] ?? key;
  const text = lang === "fr" ? frTypo(raw) : raw;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export function useDj() {
  const { language } = useLanguage();
  const t = useCallback((key: DjKey, vars?: Record<string, string | number>) => djTranslate(language, key, vars), [language]);
  return { t, language };
}
