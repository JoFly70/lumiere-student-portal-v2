DO $$
DECLARE
  t text;
  r text;
BEGIN
  FOREACH t IN ARRAY ARRAY['ops_events', 'ops_exception_states', 'ops_notifications', 'ops_runs', 'academic_import_mappings',
                           'academic_import_batches', 'academic_import_rows', 'academic_reported_records', 'calendar_events',
                           'calendar_subscriptions'] LOOP
    FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
        EXECUTE format('REVOKE ALL ON public.%I FROM %I', t, r);
      END IF;
    END LOOP;
  END LOOP;
END
$$;
