/*
  S30: operational layer + academic data imports + academic calendar. Additive and idempotent
  (IF NOT EXISTS everywhere); no existing table, column or row is changed or removed.

  One operational layer (the single authority for academic/operational events, exception state, notifications and
  background-run health). There was no earlier event or notification store in this database; the existing audit log
  (audit_logs) stays the security/compliance trail and is not duplicated: ops_events carry only identifiers, kinds and
  counts for product features (timelines, Fleet AI, diagnostics), never free-text record bodies.

    ops_events               append-only academic/operational events (dedupe_key makes emitters idempotent)
    ops_exception_states     owner acknowledgement / snooze of a derived exception (the exceptions themselves are
                             computed from records by the Control Center; resolving the record resolves them)
    ops_notifications        in-app notifications per user (+ email delivery status); dedupe_key unique
    ops_runs                 heartbeat of background runs (reminder sweep), read by Operations diagnostics

  Academic Data Import Center (extends the S05 workbook reader; never writes official results or credit):
    academic_import_mappings reusable column mappings
    academic_import_batches  one uploaded file and its workflow state (uploaded -> validated -> approved ->
                             committed -> rolled_back, or discarded) with provenance (file hash, uploader, times)
    academic_import_rows     parsed, normalised rows with their validation outcome and difference class
    academic_reported_records committed provider-/institution-REPORTED records. Tier is explicit and never
                             'verified': verified outcomes stay in hs_official_results / hs_credit_awards, written only
                             through the existing evidence-review flow.

  Academic calendar:
    calendar_events          staff-scheduled advisor meetings and support sessions (other calendar items are derived
                             live from agreements, checkpoints and orientation sessions, so nothing is duplicated)
    calendar_subscriptions   revocable iCalendar feed tokens (only a SHA-256 hash of the token is stored)

  Access: the Express server only (service role / owner connection). RLS on, no client policy, every client privilege
  revoked (consistent with 20261104110000_s25_client_write_lockdown.sql).

  Enum values first and no BEGIN/COMMIT: a new enum value cannot be used in the transaction that adds it.
*/

